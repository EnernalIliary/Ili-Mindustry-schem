"""Blueprint -> in-game tags (Mindustry v7 database tags).

Tags come from the blocks inside the blueprint: every vanilla block belongs to one
of the game's own categories (炮塔 / 生产 / 运输 / 流体 / 电力 / 防御 / 制造 / 单位 /
功能 / 逻辑), so a blueprint is tagged with the categories it actually contains.
Names are the game's zh_CN `database-tag.*` strings, not invented ones.

Logic is deliberately not a tag: a canvas drawing and a 900-line processor would
both say "逻辑" and that says nothing useful. The page filters logic by size
(logic_lines) instead, which is also what the blueprint card shows.

data/block_categories.json is generated by tools/make_categories.py.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

DATA = Path(__file__).resolve().parent / "data"

LOGIC = "logic"
MIN_SHARE = 0.03   # a single stray conveyor must not tag a whole blueprint
MIN_BLOCKS = 2
MAX_TAGS = 4


@lru_cache(maxsize=1)
def _tables() -> tuple[dict[str, str], dict[str, str]]:
    blocks_path = DATA / "block_categories.json"
    labels_path = DATA / "category_labels.json"
    blocks = json.loads(blocks_path.read_text(encoding="utf-8")) if blocks_path.is_file() else {}
    labels = json.loads(labels_path.read_text(encoding="utf-8")) if labels_path.is_file() else {}
    return blocks, labels


def category_counts(sch: dict) -> dict[str, int]:
    """How many placed blocks of each category the blueprint has."""
    blocks, _ = _tables()
    counts: dict[str, int] = {}
    for tile in sch["tiles"]:
        cat = blocks.get(tile["block"])
        if cat:
            counts[cat] = counts.get(cat, 0) + 1
    return counts


def blueprint_tags(sch: dict) -> tuple[list[str], str]:
    """(tags, primary) where tags are game labels and primary is a category key."""
    _, labels = _tables()
    counts = category_counts(sch)
    total = sum(counts.values())
    if not total:
        return [], ""

    ranked = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))
    keep = [(cat, n) for cat, n in ranked
            if cat != LOGIC and n >= max(MIN_BLOCKS, total * MIN_SHARE)][:MAX_TAGS]
    if not keep:
        fallback = next((cat for cat, _ in ranked if cat != LOGIC), "")
        keep = [(fallback, counts[fallback])] if fallback else []

    primary = next((cat for cat, _ in ranked if cat != LOGIC), ranked[0][0])
    return [labels.get(cat, cat) for cat, _ in keep], primary
